-- 0019: unannounced positions, "Your move" (unannounced.py,
-- docs/specs/2026-10-17-learning-loop-design.md part 4). Every answer is logged, the day's
-- first one per position judged for the noticing rate; nothing here is scheduled.
CREATE TABLE unannounced_answers (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      INTEGER NOT NULL DEFAULT app_user() REFERENCES users ON DELETE CASCADE,
    game_id      INTEGER NOT NULL,
    ply          INTEGER NOT NULL,
    kind         TEXT NOT NULL CHECK (kind IN ('critical', 'calm')),
    answer_uci   TEXT NOT NULL,
    correct      BOOLEAN NOT NULL,
    answered_at  TEXT NOT NULL,      -- ISO-8601 UTC
    FOREIGN KEY (user_id, game_id, ply) REFERENCES moves (user_id, game_id, ply) ON DELETE CASCADE
);
ALTER TABLE unannounced_answers ENABLE ROW LEVEL SECURITY;
CREATE POLICY own_rows ON unannounced_answers USING (user_id = app_user()) WITH CHECK (user_id = app_user());
CREATE INDEX unannounced_answers_user_at ON unannounced_answers (user_id, answered_at);
