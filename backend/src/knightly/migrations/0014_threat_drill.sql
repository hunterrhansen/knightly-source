-- 0014: the "What do they threaten?" drill (drill.py,
-- docs/specs/2026-10-16-safety-habit-training-design.md). Each item is one of your positions:
-- 'threat' (you missed a threat there; its answer is the threat set), 'calm' (no threat; the
-- answer is "No threat") or 'skip' (looked at for calm and found a threat: never served, never
-- searched again). Scheduled with FSRS like cards; threat_reviews logs every answer.
CREATE TABLE threat_cards (
    user_id           INTEGER NOT NULL DEFAULT app_user() REFERENCES users ON DELETE CASCADE,
    game_id           INTEGER NOT NULL,
    ply               INTEGER NOT NULL,
    kind              TEXT NOT NULL CHECK (kind IN ('threat', 'calm', 'skip')),
    threats           JSONB NOT NULL DEFAULT '[]',
    added_at          TEXT NOT NULL DEFAULT iso_now(),
    due               TEXT,          -- YYYY-MM-DD (local) of the next review; NULL = new
    fsrs              TEXT,          -- FSRS card state (JSON); NULL = new
    reviews           INTEGER NOT NULL DEFAULT 0,
    lapses            INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (user_id, game_id, ply),
    FOREIGN KEY (user_id, game_id, ply) REFERENCES moves (user_id, game_id, ply) ON DELETE CASCADE
);
ALTER TABLE threat_cards ENABLE ROW LEVEL SECURITY;
CREATE POLICY own_rows ON threat_cards USING (user_id = app_user()) WITH CHECK (user_id = app_user());

CREATE TABLE threat_reviews (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      INTEGER NOT NULL DEFAULT app_user() REFERENCES users ON DELETE CASCADE,
    game_id      INTEGER NOT NULL,
    ply          INTEGER NOT NULL,
    reviewed_at  TEXT NOT NULL,      -- ISO-8601 UTC
    answer       TEXT NOT NULL,      -- the threat move played (UCI), or 'none'
    correct      BOOLEAN NOT NULL,
    rating       TEXT,               -- the FSRS rating, on the day's first answer only
    FOREIGN KEY (user_id, game_id, ply) REFERENCES threat_cards (user_id, game_id, ply) ON DELETE CASCADE
);
ALTER TABLE threat_reviews ENABLE ROW LEVEL SECURITY;
CREATE POLICY own_rows ON threat_reviews USING (user_id = app_user()) WITH CHECK (user_id = app_user());
CREATE INDEX threat_reviews_user_at ON threat_reviews (user_id, reviewed_at);
